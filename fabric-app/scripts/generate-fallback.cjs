// Turns the production extract (snapshot.json) into a typed TS module that the
// console falls back to when the Fabric SQL backend is unreachable -- for
// example while the Fabric capacity hosting it is paused. The UI labels the
// rows as a snapshot; they are never presented as live data.
//
//   node scripts/generate-fallback.cjs
const fs = require('node:fs');
const path = require('node:path');

const snapshot = require('../snapshot.json');

const str = (value) => JSON.stringify(value == null ? '' : String(value));
const iso = (value) => (value ? new Date(value).toISOString() : '');
const num = (value) => JSON.stringify(String(value ?? 0));

// Mirrors AdminConsoleService.NeedsAttention in MimamoriTai.Web.
const needsAttention = (h) =>
  Number(h.FailedAlertsInWindow) > 0 ||
  h.SwitchBotStatus === 'Error' ||
  (h.DataSourceMode === 'Production' && Number(h.ActiveLineRecipients) === 0);

const capturedAt = iso(snapshot.capturedAt || Date.now());

const households = snapshot.households
  .map(
    (h) => `  {
    id: ${str(h.HouseholdId)},
    householdId: ${str(h.HouseholdId)},
    name: ${str(h.Name)},
    dataSourceMode: ${str(h.DataSourceMode)},
    memberCount: ${num(h.MemberCount)},
    residentCount: ${num(h.ResidentCount)},
    deviceCount: ${num(h.DeviceCount)},
    lastEventUtc: ${str(iso(h.LastEventUtc))},
    switchBotStatus: ${str(h.SwitchBotStatus)},
    switchBotError: ${str(h.SwitchBotError)},
    activeLineRecipients: ${num(h.ActiveLineRecipients)},
    alertsInWindow: ${num(h.AlertsInWindow)},
    failedAlertsInWindow: ${num(h.FailedAlertsInWindow)},
    latestRiskLevel: ${str(h.LatestRiskLevel)},
    needsAttention: ${needsAttention(h)},
    capturedAt: new Date(${str(capturedAt)}),
    powerTodayWh: ${num(h.PowerTodayWh)},
    powerBaselineWh: ${h.PowerBaselineWh == null ? str('') : num(h.PowerBaselineWh)},
    powerTrend: ${str(h.PowerTrend || 'Unknown')},
  },`
  )
  .join('\n');

const alerts = snapshot.alerts
  .map(
    (a) => `  {
    id: ${str(a.AlertId)},
    householdId: ${str(a.HouseholdId)},
    householdName: ${str(a.HouseholdName)},
    riskLevel: ${str(a.RiskLevel)},
    score: ${num(a.Score)},
    reason: ${str(a.Reason)},
    success: ${a.Success === true},
    error: ${str(a.Error)},
    sentAt: new Date(${str(iso(a.SentAtUtc))}),
  },`
  )
  .join('\n');

const activity = snapshot.activity
  .map(
    (b, index) =>
      `  { id: ${str(`snap-${index}`)}, householdId: ${str(b.HouseholdId)}, householdName: ${str(
        b.HouseholdName
      )}, deviceId: ${str(b.DeviceId)}, deviceName: ${str(b.DeviceName)}, deviceType: ${str(b.DeviceType)}, bucketStart: new Date(${str(
        iso(b.BucketStart)
      )}), eventCount: ${num(b.EventCount)}, onCount: ${num(b.OnCount)}, source: ${str(b.Source)}, energyWh: ${str(b.EnergyWh ?? '')} },`
  )
  .join('\n');

const aiCalls = (snapshot.aiCalls || [])
  .map(
    (c, index) =>
      `  { id: ${str(`snap-ai-${index}`)}, purpose: ${str(c.Purpose)}, router: ${str(
        c.Router
      )}, resolvedModel: ${str(c.ResolvedModel)}, callCount: ${num(
        c.CallCount
      )}, successCount: ${num(c.SuccessCount)}, avgDurationMs: ${num(
        c.AvgDurationMs
      )}, lastCalledAt: new Date(${str(iso(c.LastCalledAt))}) },`
  )
  .join('\n');

const body = `// AUTO-GENERATED by scripts/generate-fallback.cjs -- do not edit by hand.
//
// Real rows extracted read-only from the production Azure SQL database
// (schema \`mimamori\`) behind https://<your-app>.azurewebsites.net/.
// They are bundled so the console still renders when the Fabric SQL backend is
// unavailable -- most often because the Fabric capacity hosting it is paused.
//
// This is a point-in-time snapshot, NOT live data. Whenever these rows are used
// the UI says so explicitly. Never present them as a live Fabric read.
import type { ActivityRow, AiRouterCallRow, AlertRow, HouseholdRow } from './monitoring';

export const SNAPSHOT_CAPTURED_AT = new Date(${str(capturedAt)});

export const SNAPSHOT_HOUSEHOLDS: HouseholdRow[] = [
${households}
];

export const SNAPSHOT_ALERTS: AlertRow[] = [
${alerts}
];

export const SNAPSHOT_ACTIVITY: ActivityRow[] = [
${activity}
];

export const SNAPSHOT_AI_CALLS: AiRouterCallRow[] = [
${aiCalls}
];
`;

const target = path.join(__dirname, '..', 'src', 'services', 'snapshotFallback.ts');
fs.writeFileSync(target, body);
console.log(
  `wrote ${path.relative(process.cwd(), target)}: ` +
    `${snapshot.households.length} households, ${snapshot.alerts.length} alerts, ` +
    `${snapshot.activity.length} activity buckets, ` +
    `${(snapshot.aiCalls || []).length} AI router groups`
);
